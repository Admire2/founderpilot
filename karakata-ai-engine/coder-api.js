require('dotenv').config();
const express = require('express');
const cors = require('cors');
const fs = require('fs');
const path = require('path');
const { createClient } = require('@supabase/supabase-js');
const OpenAI = require('openai');

const app = express();
app.use(cors());
app.use(express.json({ limit: '10mb' }));

const supabase = createClient(process.env.SUPABASE_URL, process.env.SUPABASE_ANON_KEY);
const openai = new OpenAI({ apiKey: process.env.OPENAI_API_KEY || 'sk-disabled' });

const PROJECTS_DIR = path.join(__dirname, 'kara_generated_projects');
if (!fs.existsSync(PROJECTS_DIR)) fs.mkdirSync(PROJECTS_DIR);

// Offline demo template (works with ZERO credits)
function demoProject(description) {
  return {
    project_name: 'kara-starter-api',
    description: description,
    files: [
      { path: 'package.json', content: JSON.stringify({ name: 'kara-starter-api', version: '1.0.0', main: 'index.js', scripts: { start: 'node index.js' }, dependencies: { express: '^4.18.2' } }, null, 2) },
      { path: 'index.js', content: "const express = require('express');\nconst app = express();\napp.use(express.json());\nlet todos = [];\napp.get('/todos', (req,res)=>res.json(todos));\napp.post('/todos', (req,res)=>{ todos.push(req.body); res.status(201).json(req.body); });\napp.listen(4000, ()=>console.log('Kara starter running on 4000'));\n" },
      { path: 'README.md', content: '# Kara Starter API\nGenerated by Kara Coder (offline demo mode).\nRun: npm install && npm start\n' }
    ],
    setup_commands: ['npm install'],
    run_commands: ['npm start']
  };
}

async function generateWithAI(description) {
  const prompt = `You are Kara Coder, an elite AI software engineer. Generate a COMPLETE, runnable project for the request below.
Respond ONLY in valid JSON:
{ "project_name": "kebab-case-name", "description": "...", "files": [{"path":"relative/path","content":"full file code"}], "setup_commands": ["npm install"], "run_commands": ["npm start"] }

Project request: ${description}`;
  const response = await openai.chat.completions.create({
    model: 'gpt-4o',
    messages: [{ role: 'user', content: prompt }],
    temperature: 0.2,
    response_format: { type: 'json_object' }
  });
  return JSON.parse(response.choices[0].message.content);
}

// 1. GENERATE: Idea -> Full Codebase Plan
app.post('/api/v1/coder/generate', async (req, res) => {
  try {
    const { description } = req.body;
    if (!description) return res.status(400).json({ error: 'description is required' });
    let project, mode = 'ai';
    try { project = await generateWithAI(description); }
    catch (e) { mode = 'demo_offline'; project = demoProject(description); }

    const { data } = await supabase.from('coder_projects').insert([{ name: project.project_name, description, files: project.files, status: 'generated' }]).select().single();
    res.json({ success: true, mode, project, db_id: data ? data.id : null });
  } catch (error) { res.status(500).json({ success: false, error: error.message }); }
});

// 2. SCAFFOLD: Write the project to disk (Beginning to Finish!)
app.post('/api/v1/coder/scaffold', async (req, res) => {
  try {
    const { project } = req.body;
    const safeName = String(project.project_name).replace(/[^a-zA-Z0-9-_]/g, '_');
    const target = path.join(PROJECTS_DIR, safeName);
    fs.mkdirSync(target, { recursive: true });
    const written = [];
    for (const f of project.files) {
      const filePath = path.join(target, f.path);
      fs.mkdirSync(path.dirname(filePath), { recursive: true });
      fs.writeFileSync(filePath, f.content, 'utf8');
      written.push(f.path);
    }
    await supabase.from('coder_projects').update({ status: 'scaffolded' }).eq('name', project.project_name);
    res.json({ success: true, message: `Project scaffolded at ${target}`, files_written: written });
  } catch (error) { res.status(500).json({ success: false, error: error.message }); }
});

// 3. KARA CHAT: Iterative pair-programmer with memory
app.post('/api/v1/coder/chat', async (req, res) => {
  try {
    const { message, history } = req.body;
    let reply, mode = 'ai';
    try {
      const messages = [
        { role: 'system', content: 'You are Kara Coder Chat, an elite AI pair-programmer. Answer concisely with code blocks when needed.' },
        ...(history || []),
        { role: 'user', content: message }
      ];
      const response = await openai.chat.completions.create({ model: 'gpt-4o', messages, temperature: 0.2 });
      reply = response.choices[0].message.content;
    } catch (e) {
      mode = 'demo_offline';
      reply = '[Kara Coder Demo Mode] AI credits not active yet. Once credits are added I will answer fully. Your request: ' + message;
    }
    res.json({ success: true, mode, reply });
  } catch (error) { res.status(500).json({ success: false, error: error.message }); }
});

const PORT = process.env.CODER_PORT || 3019;
app.listen(PORT, () => console.log(`👩‍ Kara Coder & Kara Chat API running on http://localhost:${PORT}`));
